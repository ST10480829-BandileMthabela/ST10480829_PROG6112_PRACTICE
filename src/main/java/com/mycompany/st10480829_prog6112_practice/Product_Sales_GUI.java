    private int[][] captureSalesData() {

    // Create a 2D array.
    int[][] salesData = new int[2][2];

    salesData[0][0] = 520; 
    salesData[0][1] = 380;
    salesData[0][2] = 150;
    
    salesData[1][0] = 610; 
    salesData[1][1] = 340;
    salesData[1][2] = 210;
    
    salesData[2][0] = 450; 
    salesData[2][1] = 290;
    salesData[2][2] = 200;
    
    // Validate every mark.
    for (int row = 0; row < salesData.length; row++) {

        for (int col = 0; col < salesData[row].length; col++) {
            // Marks must be between 0 and 100.
            if (salesData[row][col] < 0 || salesData[row][col] > 100) {
                throw new IllegalArgumentException(
                        "Invalid");
            }
        }
    }

    // Return the completed array.
    return salesData;
}

